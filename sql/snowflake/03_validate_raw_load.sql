SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT TERRITORY_ID) AS UNIQUE_TERRITORIES,
    COUNT(LOADED_AT) AS RECORDS_WITH_LOAD_TIMESTAMP
FROM ENTERPRISE_SALES_DW.RAW.TERRITORIES;

SELECT *
FROM ENTERPRISE_SALES_DW.RAW.TERRITORIES
ORDER BY TERRITORY_ID
LIMIT 10;


-- ============================================================
-- Validate record counts across all RAW tables
-- ============================================================

SELECT 'TERRITORIES' AS TABLE_NAME, COUNT(*) AS RECORD_COUNT
FROM RAW.TERRITORIES

UNION ALL

SELECT 'SALES_REPS', COUNT(*)
FROM RAW.SALES_REPS

UNION ALL

SELECT 'PRODUCT_CATEGORIES', COUNT(*)
FROM RAW.PRODUCT_CATEGORIES

UNION ALL

SELECT 'PRODUCTS', COUNT(*)
FROM RAW.PRODUCTS

UNION ALL

SELECT 'CUSTOMERS', COUNT(*)
FROM RAW.CUSTOMERS

UNION ALL

SELECT 'ORDERS', COUNT(*)
FROM RAW.ORDERS

UNION ALL

SELECT 'ORDER_ITEMS', COUNT(*)
FROM RAW.ORDER_ITEMS;