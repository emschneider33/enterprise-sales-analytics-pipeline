
-- ============================================================
-- Test: Monthly Sales Mart Financial Reconciliation
-- Expected: Zero mismatched records
-- ============================================================

WITH expected AS (

    SELECT
        DATE_TRUNC('MONTH', ORDER_DATE)::DATE
            AS MONTH_START_DATE,

        ORDER_STATUS,

        COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
        COUNT(*) AS TOTAL_LINE_ITEMS,
        SUM(QUANTITY) AS TOTAL_UNITS,

        SUM(GROSS_SALES_AMOUNT) AS GROSS_SALES,
        SUM(DISCOUNT_AMOUNT) AS TOTAL_DISCOUNTS,
        SUM(NET_SALES_AMOUNT) AS NET_SALES,
        SUM(TOTAL_COST_AMOUNT) AS TOTAL_COST,
        SUM(GROSS_PROFIT_AMOUNT) AS GROSS_PROFIT,

        ROUND(
            SUM(GROSS_PROFIT_AMOUNT)
            / NULLIF(SUM(NET_SALES_AMOUNT), 0) * 100,
            2
        ) AS GROSS_MARGIN_PCT

    FROM {{ ref('fact_sales') }}

    GROUP BY 1, 2

)

SELECT
    COALESCE(e.MONTH_START_DATE, m.MONTH_START_DATE)
        AS MONTH_START_DATE,

    COALESCE(e.ORDER_STATUS, m.ORDER_STATUS)
        AS ORDER_STATUS

FROM expected e

FULL OUTER JOIN {{ ref('mart_monthly_sales') }} m
    ON e.MONTH_START_DATE = m.MONTH_START_DATE
    AND e.ORDER_STATUS = m.ORDER_STATUS

WHERE
    e.MONTH_START_DATE IS NULL
    OR m.MONTH_START_DATE IS NULL

    OR e.TOTAL_ORDERS IS DISTINCT FROM m.TOTAL_ORDERS
    OR e.TOTAL_LINE_ITEMS IS DISTINCT FROM m.TOTAL_LINE_ITEMS
    OR e.TOTAL_UNITS IS DISTINCT FROM m.TOTAL_UNITS

    OR e.GROSS_SALES IS DISTINCT FROM m.GROSS_SALES
    OR e.TOTAL_DISCOUNTS IS DISTINCT FROM m.TOTAL_DISCOUNTS
    OR e.NET_SALES IS DISTINCT FROM m.NET_SALES
    OR e.TOTAL_COST IS DISTINCT FROM m.TOTAL_COST
    OR e.GROSS_PROFIT IS DISTINCT FROM m.GROSS_PROFIT
    OR e.GROSS_MARGIN_PCT IS DISTINCT FROM m.GROSS_MARGIN_PCT
